// fontsource パッケージ（OFL-1.1）から必要な woff2 と LICENSE を public/fonts へコピーし、fonts.css を生成する。
// 実行: pnpm fonts:prepare
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync, rmSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const webDir = join(root, 'apps', 'web');
const require = createRequire(join(webDir, 'package.json'));
const outDir = join(webDir, 'public', 'fonts');

/** family → { pkg, weights } */
const FONTS = [
  { family: 'Noto Sans JP', pkg: '@fontsource/noto-sans-jp', weights: [400, 700], source: 'https://fonts.google.com/noto/specimen/Noto+Sans+JP' },
  { family: 'Noto Serif JP', pkg: '@fontsource/noto-serif-jp', weights: [400, 600], source: 'https://fonts.google.com/noto/specimen/Noto+Serif+JP' },
  { family: 'Caveat', pkg: '@fontsource/caveat', weights: [400, 700], source: 'https://fonts.google.com/specimen/Caveat' },
  { family: 'Allura', pkg: '@fontsource/allura', weights: [400], source: 'https://fonts.google.com/specimen/Allura' },
  { family: 'Bodoni Moda', pkg: '@fontsource/bodoni-moda', weights: [400, 600], source: 'https://fonts.google.com/specimen/Bodoni+Moda' },
];

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
let css = '/* Generated by scripts/prepare-fonts.mjs — fonts are served locally (no external requests). */\n';
const licenseIndex = ['CinemiX bundled fonts — license index', '', 'All fonts below are licensed under the SIL Open Font License 1.1 (OFL-1.1).', 'Files are copied unchanged from the fontsource npm packages (woff2 subsets).', ''];
let totalBytes = 0;
let fileCount = 0;
for (const f of FONTS) {
  const pkgDir = dirname(require.resolve(`${f.pkg}/package.json`));
  const slug = f.pkg.split('/')[1];
  const dest = join(outDir, slug);
  mkdirSync(join(dest, 'files'), { recursive: true });
  const pkgJson = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
  copyFileSync(join(pkgDir, 'LICENSE'), join(dest, 'LICENSE'));
  licenseIndex.push(`${f.family}  (package ${f.pkg}@${pkgJson.version}, ${pkgJson.license})`, `  source: ${f.source}`, `  license file: fonts/${slug}/LICENSE`, '');
  for (const w of f.weights) {
    const src = readFileSync(join(pkgDir, `${w}.css`), 'utf8');
    // woff のみの行は捨て、woff2 を残す。URL を public パスへ書き換える。
    const blocks = src.split('@font-face').slice(1);
    for (const b of blocks) {
      const m = b.match(/url\(\.\/files\/([^)]+\.woff2)\)/);
      if (!m) continue;
      const file = m[1];
      copyFileSync(join(pkgDir, 'files', file), join(dest, 'files', file));
      fileCount++;
      totalBytes += readFileSync(join(dest, 'files', file)).byteLength;
      const unicodeRange = b.match(/unicode-range:\s*([^;]+);/);
      css += `@font-face{font-family:'${f.family}';font-style:normal;font-display:swap;font-weight:${w};src:url(/fonts/${slug}/files/${file}) format('woff2');${unicodeRange ? `unicode-range:${unicodeRange[1].trim()};` : ''}}\n`;
    }
  }
}
writeFileSync(join(outDir, 'fonts.css'), css);
writeFileSync(join(outDir, 'LICENSES.txt'), licenseIndex.join('\n'));
console.log(`fonts: ${fileCount} files, ${(totalBytes / 1024 / 1024).toFixed(1)} MB -> ${outDir}`);
if (!existsSync(join(outDir, 'noto-sans-jp', 'LICENSE'))) throw new Error('license missing');
